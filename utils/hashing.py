# -*- coding: utf-8 -*-
"""
Стабильный хэш для персистентной идентификации запросов.

Встроенный hash(str) в Python рандомизируется на каждый запуск процесса
(если не задан PYTHONHASHSEED) — использовать его как ключ, сохраняемый
между перезапусками (кэш в Redis, статистика частоты запросов в JSON),
нельзя: тот же запрос после перезапуска получает другое значение, и все
ранее сохранённые данные становятся недостижимы.
"""

import hashlib


def stable_query_hash(text: str) -> int:
    """
    Детерминированный хэш строки, одинаковый во всех процессах и запусках.

    Args:
        text: Текст запроса

    Returns:
        int: Хэш, стабильный между перезапусками процесса
    """
    return int(hashlib.md5(text.encode("utf-8")).hexdigest(), 16) % (2**31)
