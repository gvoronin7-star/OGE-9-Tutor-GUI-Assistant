# -*- coding: utf-8 -*-
"""
Текст строки состояния после загрузки теста (без tkinter, чтобы проверялся тестами).

Тест может быть собран не из вопросов LLM, а из встроенного демо-банка
(LLM недоступна). Тогда в данных теста стоят поля `is_demo` и
`demo_questions`, и пользователь должен увидеть это в надписи.
"""

from typing import Any, Dict


def loaded_status_text(test: Dict[str, Any]) -> str:
    """
    Текст статуса «Тест загружен».

    Обычный тест — «✅ Тест загружен: N вопросов». Если `is_demo` истинно —
    явное предупреждение, что вопросы демонстрационные, и причина; при
    частичной подмене — сколько вопросов из N демонстрационные.
    """
    total = test["total_questions"]
    if not test.get("is_demo"):
        return f"✅ Тест загружен: {total} вопросов"

    demo = test.get("demo_questions", total)
    if demo >= total:
        return (
            f"⚠️ Тест загружен: {total} вопросов, все демонстрационные — "
            "генерация вопросов через LLM недоступна"
        )
    return (
        f"⚠️ Тест загружен: {total} вопросов, из них {demo} демонстрационных — "
        "генерация вопросов через LLM недоступна"
    )
