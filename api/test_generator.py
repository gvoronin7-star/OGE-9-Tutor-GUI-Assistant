        result = []
        for topic, questions in self._demo_questions_db().items():
            for q in questions:
                q_type = q.get("type", "")
                difficulty = type_to_difficulty.get(q_type, "medium")
                result.append(({**q, "difficulty": difficulty}, topic))

        return result
