def _topic_id(title: str) -> str:
    """Стабильный id темы для JSON/Dart — латиница, без пробелов."""
    mapping = {
        "Человек и общество": "society",
        "Сфера духовной культуры": "culture",
        "Экономика": "economy",
        "Социальная сфера": "social",
        "Политика": "politics",
        "Право": "law",
    }
    return mapping[title]


def build_topics_json() -> List[Dict[str, Any]]:
    return [
        {"id": _topic_id(title), "title": title, "article": ARTICLES[title]}
        for title in TOPICS
    ]


def build_questions_json() -> List[Dict[str, Any]]:
    result = []
    for title in TOPICS:
        topic_id = _topic_id(title)
        for question in QUESTIONS[title]:
            result.append({"topic_id": topic_id, "topic_title": title, **question})
    return result


def main() -> None:
    missing_articles = [t for t in TOPICS if t not in ARTICLES]
    missing_questions = [t for t in TOPICS if t not in QUESTIONS]
    if missing_articles or missing_questions:
        raise SystemExit(
            f"Нет статьи для тем: {missing_articles}; "
            f"нет вопросов для тем: {missing_questions}"
        )

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    topics_path = OUTPUT_DIR / "topics.json"
    topics_path.write_text(
        json.dumps(build_topics_json(), ensure_ascii=False, indent=2),
        encoding="utf-8",
    )

    questions = build_questions_json()
    questions_path = OUTPUT_DIR / "questions.json"
    questions_path.write_text(
        json.dumps(questions, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )

    print(f"Написано {len(TOPICS)} тем -> {topics_path}")
    print(f"Написано {len(questions)} вопросов -> {questions_path}")


if __name__ == "__main__":
    main()
